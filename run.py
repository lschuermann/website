#!/usr/bin/env python3

import os, sys, time
import tempfile
import unittest.mock
import socket
import _thread as thread
import pyinotify
import asyncio
import contextlib
import re
import shutil
import threading
from http.server import HTTPServer, SimpleHTTPRequestHandler

last_modified = time.time()


INTERACTIVE = sys.stderr.isatty() and os.environ.get("TERM") != "dumb"
COLOR = INTERACTIVE and "NO_COLOR" not in os.environ
LOG_LOCK = threading.Lock()
ANSI_ESCAPE = re.compile(r"\x1b\[[0-?]*[ -/]*[@-~]")
COLORS = {"build": "33", "ready": "32", "error": "31", "http": "36", "nix": "90"}


def log(kind, message, *, transient=False):
    # Keep subprocess output and request paths on one terminal-width line.
    message = ANSI_ESCAPE.sub("", str(message))
    message = "".join(c if c.isprintable() else " " for c in message)
    line = f"{time.strftime('%H:%M:%S')} {kind.upper():5} {message}"
    width = max(20, shutil.get_terminal_size(fallback=(120, 24)).columns - 1)
    if len(line) > width:
        line = line[: width - 1] + "…"
    if COLOR:
        line = f"\033[{COLORS.get(kind, '0')}m{line}\033[0m"
    with LOG_LOCK:
        prefix = "\r\033[2K" if INTERACTIVE else ""
        print(prefix + line, file=sys.stderr, end="" if transient else "\n", flush=True)


async def build_progress(started):
    frames = "|/-\\"
    index = 0
    while True:
        log(
            "build",
            f"{frames[index % len(frames)]} Rebuilding… {time.monotonic() - started:.1f}s",
            transient=True,
        )
        index += 1
        await asyncio.sleep(0.1)


def serve_dir(directory):
    last_modified = time.time()

    class RequestHandler(SimpleHTTPRequestHandler):
        def __init__(self, *args, **kwargs):
            global last_modified
            self.os_fstat_unpatched = os.fstat
            self.last_modified = last_modified

            return SimpleHTTPRequestHandler.__init__(
                self, *args, directory=directory, **kwargs
            )

        def fake_fstat(self, fileno):
            class StatResultWrapper:
                def __init__(self, base, override_mtime):
                    self.base = base
                    self.override_mtime = override_mtime

                def __getattr__(self, name):
                    if name == "st_mtime":
                        return self.override_mtime
                    else:
                        return getattr(self.base, name)

                def __getitem__(self, key):
                    return self.base[key]

            return StatResultWrapper(
                self.os_fstat_unpatched(fileno),
                self.last_modified,
            )

        def send_head(self, *args, **kwargs):
            with unittest.mock.patch("os.fstat", side_effect=self.fake_fstat):
                return SimpleHTTPRequestHandler.send_head(self, *args, **kwargs)

        def log_message(self, fmt, *args):
            log("http", fmt % args)

        # Avoid propagating socket errors, such as when the client closes
        # the connection prematurely.
        def handle(self):
            try:
                SimpleHTTPRequestHandler.handle(self)
            except socket.error:
                pass

    httpd = HTTPServer(("localhost", 8080), RequestHandler)

    httpd.serve_forever()


async def serve():
    global last_modified

    with tempfile.TemporaryDirectory() as tmpdir:
        resultdir = tmpdir + "/result"
        log("ready", "Preview at http://localhost:8080 · Ctrl-C to stop")
        thread.start_new_thread(serve_dir, (resultdir,))

        build_event = asyncio.Event()
        build_event.set()
        changed_paths = set()

        class EventProcessor(pyinotify.ProcessEvent):
            _methods = [
                "IN_CREATE",
                "IN_CLOSE_WRITE",
                "IN_DELETE",
                "IN_DELETE_SELF",
                "IN_MODIFY",
                "IN_MOVE_SELF",
                "IN_MOVED_FROM",
                "IN_MOVED_TO",
                "IN_Q_OVERFLOW",
                "IN_UNMOUNT",
            ]

        def process_generator(cls, method):
            def _method_name(self, event):
                changed_paths.add(os.path.relpath(event.pathname))
                build_event.set()

            _method_name.__name__ = "process_{}".format(method)
            setattr(cls, _method_name.__name__, _method_name)

        for method in EventProcessor._methods:
            process_generator(EventProcessor, method)

        watch_manager = pyinotify.WatchManager()
        event_notifier = pyinotify.AsyncioNotifier(
            watch_manager, asyncio.get_event_loop(), default_proc_fun=EventProcessor()
        )

        watch_manager.add_watch(
            os.path.abspath("./"), pyinotify.ALL_EVENTS, rec=True, auto_add=True
        )

        while True:
            # Wait for changes, then kick off a rebuild
            await build_event.wait()
            # Coalesce the multiple filesystem events generated by one save.
            await asyncio.sleep(0.15)
            build_event.clear()
            changes = sorted(changed_paths)
            changed_paths.clear()
            if changes:
                log("build", f"Changed {len(changes)} path(s): {', '.join(changes)}")
            started = time.monotonic()
            log("build", "Rebuilding…")
            build_proc = await asyncio.create_subprocess_exec(
                *[
                    "nix",
                    "build",
                    ".#preview",
                    "--out-link",
                    resultdir,
                    "--no-write-lock-file",
                ],
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.STDOUT,
            )
            progress = (
                asyncio.create_task(build_progress(started)) if INTERACTIVE else None
            )
            try:
                async for line in build_proc.stdout:
                    log("nix", line.decode(errors="replace").rstrip())
                returncode = await build_proc.wait()
            finally:
                if progress is not None:
                    progress.cancel()
                    with contextlib.suppress(asyncio.CancelledError):
                        await progress
            elapsed = time.monotonic() - started
            if returncode == 0:
                last_modified = time.time()
                log("ready", f"Built in {elapsed:.1f}s · http://localhost:8080")
            else:
                log(
                    "error",
                    f"Build failed (exit {returncode}) after {elapsed:.1f}s; waiting for changes",
                )


def main():
    try:
        asyncio.run(serve())
    except KeyboardInterrupt:
        log("ready", "Preview stopped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
